let marks =Number(prompt("Enter the marks "));
if(marks>80){
    document.write("Your Grade in A ");
}
else if(marks>=75){
    document.write("You Grade is B+ ")
}
else if(marks>=60){
    document.write("Your Grade is B")
}
else if(marks>=40){
    document.write("Your Grade is C");
}
else{
    document.write("Fail");
}