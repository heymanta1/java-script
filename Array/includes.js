// includes() — Check if an item exists

// includes() checks whether an array contains a particular value.

// It returns either:

// true → item exists
// false → item doesn't exist

let fruits = ["Apple", "Banana", "Mango"];

console.log(fruits.includes("Mango"));

let fruitss = ["Apple", "Banana", "Mango"];

console.log(fruitss.includes("Orange"));